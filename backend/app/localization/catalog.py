#: 少数缩写在美化时需要保持整体大写，不能被逐词首字母大写规则拆散。
_ACRONYM_OVERRIDES: dict[str, str] = {
    "AI": "AI",
}


def _beautify_status_code(code: str) -> str:
    """`"NOT_RUN"` -> `"Not Run"`；`"AI_GENERATED"` -> `"AI Generated"`。"""

    words = code.split("_")
    return " ".join(_ACRONYM_OVERRIDES.get(word, word.capitalize()) for word in words)


_STATUS_LABELS: dict[str, str] = {code: _beautify_status_code(code) for code in _STATUS_CODES}


def _merge_translations(*groups: dict[str, str]) -> dict[str, str]:
    """合并各来源分组；同一 key 出现在多组时必须给出完全相同的译文。

    真实出现的重复 key（如 "日期"/"类目"/"退款金额" 同时是维度标签和明细列
    标签）本身就该翻译成同一个词，这里的冲突检测只是防止后续编辑分组时
    不小心让同一个中文/码在两处译出两种不同的英文。
    """

    merged: dict[str, str] = {}
    for group in groups:
        for key, value in group.items():
            existing = merged.get(key)
            if existing is not None and existing != value:
                raise ValueError(
                    f"确定性词典冲突：{key!r} 同时被译为 {existing!r} 和 {value!r}"
                )
            merged[key] = value
    return merged


