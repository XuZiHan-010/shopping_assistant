def localize_catalog_value(value: str, target_locale: SupportedLocale) -> str | None:
    """零 LLM 的确定性词典查找。

    - 未命中词典：返回 `None`，调用方据此判断需要走 LLM 批量翻译路径；
    - 命中且目标语言是 `zh-CN`：原样返回 `value`（词典的 key 本身就是当前
      展示形态，不需要也不应该改写）；
    - 命中且目标语言是 `en-US`：返回词典登记的英文译文。
    """

    if value not in _TRANSLATIONS:
        return None
    if target_locale is SupportedLocale.ZH_CN:
        return value
    return _TRANSLATIONS[value]
